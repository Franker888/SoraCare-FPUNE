-- =========================================================
-- 6. ACTUALIZACIÓN AUTOMÁTICA DE FECHAS
-- =========================================================

CREATE OR REPLACE FUNCTION
    soracare.actualizar_fecha_documento()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS
    trg_actualizar_fecha_tipo_documento
ON soracare.tipos_documento;

CREATE TRIGGER trg_actualizar_fecha_tipo_documento
    BEFORE UPDATE
    ON soracare.tipos_documento
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_documento();


DROP TRIGGER IF EXISTS
    trg_actualizar_fecha_documento
ON soracare.documentos;

CREATE TRIGGER trg_actualizar_fecha_documento
    BEFORE UPDATE
    ON soracare.documentos
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_documento();


