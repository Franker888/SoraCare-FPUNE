-- =========================================================
-- 1. CATÁLOGO DE TIPOS DE DOCUMENTO
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.tipos_documento (
                                                        id_tipo_documento SMALLINT
                                                        GENERATED BY DEFAULT AS IDENTITY,

                                                        codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),

    categoria VARCHAR(30) NOT NULL,

    requiere_firma BOOLEAN NOT NULL DEFAULT FALSE,
    confidencial_por_defecto BOOLEAN NOT NULL DEFAULT TRUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_creacion TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_actualizacion TIMESTAMP WITH TIME ZONE
                                      NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT pk_tipos_documento
                                      PRIMARY KEY (id_tipo_documento),

    CONSTRAINT ux_tipos_documento_codigo
    UNIQUE (codigo),

    CONSTRAINT ck_tipos_documento_categoria
    CHECK (
              categoria IN (
              'CLINICO',
              'ADMINISTRATIVO',
              'FINANCIERO',
              'IDENTIDAD',
              'OTRO'
                           )
    )
    );


-- =========================================================
-- 2. DOCUMENTOS
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.documentos (
                                                   id_documento BIGINT
                                                   GENERATED BY DEFAULT AS IDENTITY,

                                                   id_tipo_documento SMALLINT NOT NULL,

    -- Relaciones opcionales con otros módulos
                                                   id_paciente BIGINT,
                                                   id_atencion BIGINT,
                                                   id_receta BIGINT,
                                                   id_pago BIGINT,

    -- Usuario que cargó o generó el documento
                                                   id_usuario_carga BIGINT,

                                                   codigo_documento VARCHAR(60) NOT NULL,

    nombre_archivo VARCHAR(255) NOT NULL,
    nombre_original VARCHAR(255),

    extension VARCHAR(15),
    tipo_mime VARCHAR(120),
    tamano_bytes BIGINT,

    -- El archivo se almacenará fuera de PostgreSQL.
    ruta_almacenamiento VARCHAR(1000) NOT NULL,

    -- Permitirá verificar que el archivo no fue modificado.
    hash_sha256 VARCHAR(64),

    descripcion VARCHAR(500),

    origen VARCHAR(20) NOT NULL DEFAULT 'GENERADO',
    visibilidad VARCHAR(30) NOT NULL DEFAULT 'PRIVADO',
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',

    version_documento INTEGER NOT NULL DEFAULT 1,

    confidencial BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_documento DATE,

    fecha_creacion TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_actualizacion TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_eliminacion TIMESTAMP WITH TIME ZONE,

                                    CONSTRAINT pk_documentos
                                    PRIMARY KEY (id_documento),

    CONSTRAINT ux_documentos_codigo
    UNIQUE (codigo_documento),

    CONSTRAINT fk_documentos_tipo
    FOREIGN KEY (id_tipo_documento)
    REFERENCES soracare.tipos_documento(id_tipo_documento)
                                ON UPDATE CASCADE
                                ON DELETE RESTRICT,

    CONSTRAINT fk_documentos_paciente
    FOREIGN KEY (id_paciente)
    REFERENCES soracare.pacientes(id_paciente)
                                ON UPDATE CASCADE
                                ON DELETE RESTRICT,

    CONSTRAINT fk_documentos_atencion
    FOREIGN KEY (id_atencion)
    REFERENCES soracare.atenciones_medicas(id_atencion)
                                ON UPDATE CASCADE
                                ON DELETE SET NULL,

    CONSTRAINT fk_documentos_receta
    FOREIGN KEY (id_receta)
    REFERENCES soracare.recetas_medicas(id_receta)
                                ON UPDATE CASCADE
                                ON DELETE SET NULL,

    CONSTRAINT fk_documentos_pago
    FOREIGN KEY (id_pago)
    REFERENCES soracare.pagos(id_pago)
                                ON UPDATE CASCADE
                                ON DELETE SET NULL,

    CONSTRAINT fk_documentos_usuario_carga
    FOREIGN KEY (id_usuario_carga)
    REFERENCES soracare.usuarios(id_usuario)
                                ON UPDATE CASCADE
                                ON DELETE SET NULL,

    CONSTRAINT ck_documentos_tamano
    CHECK (
              tamano_bytes IS NULL
              OR tamano_bytes >= 0
          ),

    CONSTRAINT ck_documentos_version
    CHECK (version_documento >= 1),

    CONSTRAINT ck_documentos_origen
    CHECK (
              origen IN (
              'GENERADO',
              'CARGADO',
              'IMPORTADO'
                        )
    ),

    CONSTRAINT ck_documentos_visibilidad
    CHECK (
              visibilidad IN (
              'PRIVADO',
              'PACIENTE',
              'PERSONAL_MEDICO',
              'ADMINISTRATIVO'
                             )
    ),

    CONSTRAINT ck_documentos_estado
    CHECK (
              estado IN (
              'DISPONIBLE',
              'ANULADO',
              'ARCHIVADO',
              'ELIMINADO'
                        )
    ),

    CONSTRAINT ck_documentos_hash_sha256
    CHECK (
              hash_sha256 IS NULL
              OR hash_sha256 ~ '^[0-9A-Fa-f]{64}$'
          ),

    CONSTRAINT ck_documentos_fecha_eliminacion
    CHECK (
(estado = 'ELIMINADO' AND fecha_eliminacion IS NOT NULL)
    OR
(estado <> 'ELIMINADO')
    )
    );


-- =========================================================
-- 3. REGISTRO DE ACCESOS A DOCUMENTOS
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.accesos_documentos (
                                                           id_acceso_documento BIGINT
                                                           GENERATED BY DEFAULT AS IDENTITY,

                                                           id_documento BIGINT NOT NULL,
                                                           id_usuario BIGINT,

                                                           accion VARCHAR(20) NOT NULL,

    direccion_ip INET,
    agente_usuario VARCHAR(500),

    exitoso BOOLEAN NOT NULL DEFAULT TRUE,
    detalle_error VARCHAR(500),

    fecha_acceso TIMESTAMP WITH TIME ZONE
                               NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT pk_accesos_documentos
                               PRIMARY KEY (id_acceso_documento),

    CONSTRAINT fk_accesos_documentos_documento
    FOREIGN KEY (id_documento)
    REFERENCES soracare.documentos(id_documento)
                           ON UPDATE CASCADE
                           ON DELETE CASCADE,

    CONSTRAINT fk_accesos_documentos_usuario
    FOREIGN KEY (id_usuario)
    REFERENCES soracare.usuarios(id_usuario)
                           ON UPDATE CASCADE
                           ON DELETE SET NULL,

    CONSTRAINT ck_accesos_documentos_accion
    CHECK (
              accion IN (
              'VISUALIZAR',
              'DESCARGAR',
              'IMPRIMIR',
              'COMPARTIR'
                        )
    ),

    CONSTRAINT ck_accesos_documentos_error
    CHECK (
              exitoso = TRUE
              OR detalle_error IS NOT NULL
          )
    );


