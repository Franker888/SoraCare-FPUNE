BEGIN;

-- =========================================================
-- SECUENCIA PARA CÓDIGOS DE RECETA
-- =========================================================

CREATE SEQUENCE IF NOT EXISTS soracare.recetas_codigo_seq
    START WITH 1
    INCREMENT BY 1;


-- =========================================================
-- CATÁLOGO DE MEDICAMENTOS
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.medicamentos (
                                                     id_medicamento BIGINT GENERATED BY DEFAULT AS IDENTITY,

                                                     nombre_comercial VARCHAR(120) NOT NULL,
    principio_activo VARCHAR(120) NOT NULL,
    presentacion VARCHAR(100) NOT NULL,
    concentracion VARCHAR(60),
    via_administracion VARCHAR(40) NOT NULL,

    requiere_receta BOOLEAN NOT NULL DEFAULT TRUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_medicamentos
    PRIMARY KEY (id_medicamento),

    CONSTRAINT ck_medicamentos_nombre
    CHECK (LENGTH(TRIM(nombre_comercial)) >= 2),

    CONSTRAINT ck_medicamentos_principio_activo
    CHECK (LENGTH(TRIM(principio_activo)) >= 2),

    CONSTRAINT ck_medicamentos_presentacion
    CHECK (LENGTH(TRIM(presentacion)) >= 2),

    CONSTRAINT ck_medicamentos_via
    CHECK (
              via_administracion IN (
              'ORAL',
              'INTRAVENOSA',
              'INTRAMUSCULAR',
              'SUBCUTANEA',
              'TOPICA',
              'OFTALMICA',
              'OTICA',
              'INHALATORIA',
              'RECTAL',
              'VAGINAL',
              'OTRA'
                                    )
    )
    );


-- =========================================================
-- RECETAS MÉDICAS
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.recetas_medicas (
                                                        id_receta BIGINT GENERATED BY DEFAULT AS IDENTITY,

                                                        id_atencion BIGINT NOT NULL,
                                                        id_paciente BIGINT NOT NULL,
                                                        id_medico BIGINT NOT NULL,

                                                        codigo VARCHAR(30) NOT NULL DEFAULT (
                                                                                                'RX-' ||
                                                                                                LPAD(
                                                                                                NEXTVAL('soracare.recetas_codigo_seq'::REGCLASS)::TEXT,
    10,
    '0'
    )
    ),

    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_vencimiento DATE,

    indicaciones_generales TEXT,

    estado VARCHAR(20) NOT NULL DEFAULT 'EMITIDA',

    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_recetas_medicas
    PRIMARY KEY (id_receta),

    CONSTRAINT ux_recetas_medicas_codigo
    UNIQUE (codigo),

    CONSTRAINT fk_recetas_atencion
    FOREIGN KEY (id_atencion)
    REFERENCES soracare.atenciones_medicas (id_atencion)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,

    CONSTRAINT fk_recetas_paciente
    FOREIGN KEY (id_paciente)
    REFERENCES soracare.pacientes (id_paciente)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,

    CONSTRAINT fk_recetas_medico
    FOREIGN KEY (id_medico)
    REFERENCES soracare.medicos (id_medico)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,

    CONSTRAINT ck_recetas_estado
    CHECK (
              estado IN (
              'EMITIDA',
              'DISPENSADA',
              'ANULADA',
              'VENCIDA'
                        )
    ),

    CONSTRAINT ck_recetas_vencimiento
    CHECK (
              fecha_vencimiento IS NULL
              OR fecha_vencimiento >= fecha_emision::DATE
          )
    );


-- =========================================================
-- DETALLES DE LAS RECETAS
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.recetas_detalles (
                                                         id_detalle_receta BIGINT GENERATED BY DEFAULT AS IDENTITY,

                                                         id_receta BIGINT NOT NULL,
                                                         id_medicamento BIGINT NOT NULL,

                                                         dosis VARCHAR(80) NOT NULL,
    frecuencia VARCHAR(80) NOT NULL,
    duracion_dias SMALLINT,

    cantidad NUMERIC(10, 2) NOT NULL,
    unidad VARCHAR(30) NOT NULL,

    instrucciones TEXT,

    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_recetas_detalles
    PRIMARY KEY (id_detalle_receta),

    CONSTRAINT fk_detalles_receta
    FOREIGN KEY (id_receta)
    REFERENCES soracare.recetas_medicas (id_receta)
    ON UPDATE CASCADE
    ON DELETE CASCADE,

    CONSTRAINT fk_detalles_medicamento
    FOREIGN KEY (id_medicamento)
    REFERENCES soracare.medicamentos (id_medicamento)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,

    CONSTRAINT ck_detalles_dosis
    CHECK (LENGTH(TRIM(dosis)) >= 1),

    CONSTRAINT ck_detalles_frecuencia
    CHECK (LENGTH(TRIM(frecuencia)) >= 1),

    CONSTRAINT ck_detalles_duracion
    CHECK (
              duracion_dias IS NULL
              OR duracion_dias > 0
          ),

    CONSTRAINT ck_detalles_cantidad
    CHECK (cantidad > 0),

    CONSTRAINT ck_detalles_unidad
    CHECK (LENGTH(TRIM(unidad)) >= 1)
    );


-- =========================================================
-- ÍNDICES
-- =========================================================

CREATE UNIQUE INDEX IF NOT EXISTS ux_medicamentos_identidad
    ON soracare.medicamentos (
    LOWER(nombre_comercial),
    LOWER(principio_activo),
    LOWER(presentacion),
    LOWER(COALESCE(concentracion, ''))
    );

CREATE INDEX IF NOT EXISTS ix_recetas_atencion
    ON soracare.recetas_medicas (id_atencion);

CREATE INDEX IF NOT EXISTS ix_recetas_paciente_fecha
    ON soracare.recetas_medicas (id_paciente, fecha_emision DESC);

CREATE INDEX IF NOT EXISTS ix_recetas_medico_fecha
    ON soracare.recetas_medicas (id_medico, fecha_emision DESC);

CREATE INDEX IF NOT EXISTS ix_recetas_estado
    ON soracare.recetas_medicas (estado);

CREATE INDEX IF NOT EXISTS ix_recetas_detalles_receta
    ON soracare.recetas_detalles (id_receta);

CREATE INDEX IF NOT EXISTS ix_recetas_detalles_medicamento
    ON soracare.recetas_detalles (id_medicamento);


-- =========================================================
-- VALIDAR QUE LA RECETA COINCIDA CON LA ATENCIÓN
-- =========================================================

CREATE OR REPLACE FUNCTION soracare.validar_receta_atencion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
paciente_atencion BIGINT;
    medico_atencion BIGINT;
BEGIN
SELECT
    id_paciente,
    id_medico
INTO
    paciente_atencion,
    medico_atencion
FROM soracare.atenciones_medicas
WHERE id_atencion = NEW.id_atencion;

IF NOT FOUND THEN
        RAISE EXCEPTION
            'La atención médica con ID % no existe',
            NEW.id_atencion;
END IF;

    IF paciente_atencion <> NEW.id_paciente THEN
        RAISE EXCEPTION
            'El paciente de la receta no coincide con el paciente de la atención';
END IF;

    IF medico_atencion <> NEW.id_medico THEN
        RAISE EXCEPTION
            'El médico de la receta no coincide con el médico de la atención';
END IF;

RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS trg_validar_receta_atencion
    ON soracare.recetas_medicas;

CREATE TRIGGER trg_validar_receta_atencion
    BEFORE INSERT OR UPDATE OF
    id_atencion,
                         id_paciente,
                         id_medico
                     ON soracare.recetas_medicas
                         FOR EACH ROW
                         EXECUTE FUNCTION soracare.validar_receta_atencion();


-- =========================================================
-- ACTUALIZAR FECHA DE MODIFICACIÓN
-- =========================================================

CREATE OR REPLACE FUNCTION soracare.actualizar_fecha_recetas()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS trg_actualizar_medicamento
    ON soracare.medicamentos;

CREATE TRIGGER trg_actualizar_medicamento
    BEFORE UPDATE
    ON soracare.medicamentos
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_recetas();


DROP TRIGGER IF EXISTS trg_actualizar_receta
    ON soracare.recetas_medicas;

CREATE TRIGGER trg_actualizar_receta
    BEFORE UPDATE
    ON soracare.recetas_medicas
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_recetas();


-- =========================================================
-- COMENTARIOS
-- =========================================================

COMMENT ON TABLE soracare.medicamentos IS
    'Catálogo de medicamentos disponibles para prescripción médica';

COMMENT ON TABLE soracare.recetas_medicas IS
    'Recetas emitidas por los médicos durante una atención';

COMMENT ON TABLE soracare.recetas_detalles IS
    'Medicamentos, dosis, frecuencias y duración de cada receta';

COMMENT ON COLUMN soracare.recetas_medicas.codigo IS
    'Código único generado automáticamente para identificar la receta';

COMMENT ON COLUMN soracare.recetas_medicas.estado IS
    'Estado actual de la receta: EMITIDA, DISPENSADA, ANULADA o VENCIDA';


-- =========================================================
-- PROPIETARIOS
-- =========================================================

ALTER SEQUENCE soracare.recetas_codigo_seq
    OWNER TO soracare_app;

ALTER TABLE soracare.medicamentos
    OWNER TO soracare_app;

ALTER TABLE soracare.recetas_medicas
    OWNER TO soracare_app;

ALTER TABLE soracare.recetas_detalles
    OWNER TO soracare_app;

ALTER FUNCTION soracare.validar_receta_atencion()
    OWNER TO soracare_app;

ALTER FUNCTION soracare.actualizar_fecha_recetas()
    OWNER TO soracare_app;

COMMIT;