-- =========================================================
-- PAGOS
-- Permite varios intentos de pago para una misma cita.
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.pagos (
                                              id_pago BIGINT
                                              GENERATED BY DEFAULT AS IDENTITY
                                              PRIMARY KEY,

                                              id_cita BIGINT NOT NULL,
                                              id_metodo_pago SMALLINT NOT NULL,
                                              id_estado_pago SMALLINT NOT NULL,

                                              monto NUMERIC(14, 2) NOT NULL,
    moneda CHAR(3) NOT NULL DEFAULT 'PYG',

    proveedor_pago VARCHAR(60),
    referencia_externa VARCHAR(120),
    clave_idempotencia VARCHAR(120),

    datos_proveedor JSONB NOT NULL DEFAULT '{}'::JSONB,

    fecha_vencimiento TIMESTAMP WITH TIME ZONE,
    fecha_confirmacion TIMESTAMP WITH TIME ZONE,

                                     observacion VARCHAR(500),

    creado_en TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
                                     NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT fk_pagos_citas
                                     FOREIGN KEY (id_cita)
    REFERENCES soracare.citas (id_cita),

    CONSTRAINT fk_pagos_metodos_pago
    FOREIGN KEY (id_metodo_pago)
    REFERENCES soracare.metodos_pago (id_metodo_pago),

    CONSTRAINT fk_pagos_estados_pago
    FOREIGN KEY (id_estado_pago)
    REFERENCES soracare.estados_pago (id_estado_pago),

    CONSTRAINT ck_pagos_monto_positivo
    CHECK (monto > 0),

    CONSTRAINT ck_pagos_moneda
    CHECK (moneda ~ '^[A-Z]{3}$'),

    CONSTRAINT uq_pagos_clave_idempotencia
    UNIQUE (clave_idempotencia)
    );

-- =========================================================
-- COMPROBANTES DE PAGO
-- Guarda los datos del PDF generado por la aplicación.
-- No representa todavía una factura legal/electrónica.
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.comprobantes_pago (
                                                          id_comprobante BIGINT
                                                          GENERATED BY DEFAULT AS IDENTITY
                                                          PRIMARY KEY,

                                                          id_pago BIGINT NOT NULL,
                                                          id_usuario_emisor BIGINT,

                                                          numero_comprobante VARCHAR(50) NOT NULL UNIQUE,
    tipo_comprobante VARCHAR(20) NOT NULL DEFAULT 'RECIBO',

    nombre_archivo VARCHAR(255),
    ubicacion_archivo VARCHAR(500),
    hash_sha256 CHAR(64),

    enviado_email BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_emision TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_envio_email TIMESTAMP WITH TIME ZONE,

                                    CONSTRAINT fk_comprobantes_pago_pagos
                                    FOREIGN KEY (id_pago)
    REFERENCES soracare.pagos (id_pago),

    CONSTRAINT fk_comprobantes_pago_usuarios
    FOREIGN KEY (id_usuario_emisor)
    REFERENCES soracare.usuarios (id_usuario),

    CONSTRAINT ck_comprobantes_pago_tipo
    CHECK (
              tipo_comprobante IN (
              'RECIBO',
              'CONSTANCIA',
              'NOTA_CREDITO'
                                  )
    ),

    CONSTRAINT ck_comprobantes_hash_sha256
    CHECK (
              hash_sha256 IS NULL
              OR hash_sha256 ~ '^[A-Fa-f0-9]{64}$'
          )
    );

-- =========================================================
