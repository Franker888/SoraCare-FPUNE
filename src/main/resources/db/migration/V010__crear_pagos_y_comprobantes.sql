    REFERENCES soracare.pagos (id_pago),

    CONSTRAINT fk_historial_pagos_estado_anterior
    FOREIGN KEY (id_estado_anterior)
    REFERENCES soracare.estados_pago (id_estado_pago),

    CONSTRAINT fk_historial_pagos_estado_nuevo
    FOREIGN KEY (id_estado_nuevo)
    REFERENCES soracare.estados_pago (id_estado_pago),

    CONSTRAINT fk_historial_pagos_usuario
    FOREIGN KEY (id_usuario_actor)
