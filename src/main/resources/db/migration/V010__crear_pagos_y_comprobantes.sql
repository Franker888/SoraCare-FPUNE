-- =========================================================
-- FUNCIÓN: PREPARAR EL PAGO ANTES DE GUARDARLO
-- Actualiza la fecha y registra cuándo queda confirmado.
-- =========================================================

CREATE OR REPLACE FUNCTION soracare.preparar_pago()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
codigo_estado VARCHAR(30);
BEGIN
    NEW.actualizado_en := CURRENT_TIMESTAMP;

SELECT estado.codigo
INTO codigo_estado
FROM soracare.estados_pago estado
WHERE estado.id_estado_pago = NEW.id_estado_pago;

IF codigo_estado = 'CONFIRMADO'
       AND NEW.fecha_confirmacion IS NULL THEN

        NEW.fecha_confirmacion := CURRENT_TIMESTAMP;
END IF;

RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_preparar_pago
ON soracare.pagos;

CREATE TRIGGER trg_preparar_pago
    BEFORE INSERT OR UPDATE
                         ON soracare.pagos
                         FOR EACH ROW
                         EXECUTE FUNCTION soracare.preparar_pago();

-- =========================================================
-- FUNCIÓN: REGISTRAR EL HISTORIAL DEL PAGO
-- =========================================================

CREATE OR REPLACE FUNCTION soracare.registrar_historial_estado_pago()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
usuario_actor BIGINT;
    motivo_cambio TEXT;
BEGIN
BEGIN
        usuario_actor :=
            NULLIF(
                current_setting(
                    'soracare.usuario_id',
                    TRUE
                ),
                ''
            )::BIGINT;
EXCEPTION
        WHEN invalid_text_representation THEN
            usuario_actor := NULL;
END;

    motivo_cambio :=
        NULLIF(
            current_setting(
                'soracare.motivo_pago',
                TRUE
            ),
            ''
        );

    IF TG_OP = 'INSERT' THEN
        INSERT INTO soracare.historial_estados_pagos (
            id_pago,
            id_estado_anterior,
            id_estado_nuevo,
            id_usuario_actor,
            motivo
        )
        VALUES (
            NEW.id_pago,
            NULL,
            NEW.id_estado_pago,
            usuario_actor,
            COALESCE(
                motivo_cambio,
                'Creación del pago'
            )
        );

    ELSIF NEW.id_estado_pago
          IS DISTINCT FROM OLD.id_estado_pago THEN

        INSERT INTO soracare.historial_estados_pagos (
            id_pago,
            id_estado_anterior,
            id_estado_nuevo,
            id_usuario_actor,
            motivo
        )
        VALUES (
            NEW.id_pago,
            OLD.id_estado_pago,
            NEW.id_estado_pago,
            usuario_actor,
            COALESCE(
                motivo_cambio,
                'Cambio de estado del pago'
            )
        );
END IF;

RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_historial_estado_pago
ON soracare.pagos;

CREATE TRIGGER trg_historial_estado_pago
    AFTER INSERT OR UPDATE OF id_estado_pago
                    ON soracare.pagos
                        FOR EACH ROW
                        EXECUTE FUNCTION soracare.registrar_historial_estado_pago();

