-- =========================================================
-- 1. CATÁLOGO DE TIPOS DE REPORTE
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.tipos_reportes
(
    id_tipo_reporte SMALLINT
    GENERATED BY DEFAULT AS IDENTITY
    PRIMARY KEY,

    codigo VARCHAR(80) NOT NULL,

    nombre VARCHAR(120) NOT NULL,

    descripcion VARCHAR(500),

    formato_predeterminado VARCHAR(10)
    NOT NULL DEFAULT 'PDF',

    activo BOOLEAN
    NOT NULL DEFAULT TRUE,

    fecha_creacion TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_actualizacion TIMESTAMP WITH TIME ZONE
                                      NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT ux_tipos_reportes_codigo
                                      UNIQUE (codigo),

    CONSTRAINT ck_tipos_reportes_formato
    CHECK (
              formato_predeterminado IN ('PDF', 'CSV', 'XLSX')
    )
    );


-- =========================================================
-- 2. REPORTES SOLICITADOS O GENERADOS
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.reportes_generados
(
    id_reporte BIGINT
    GENERATED BY DEFAULT AS IDENTITY
    PRIMARY KEY,

    id_tipo_reporte SMALLINT NOT NULL,

    id_usuario_solicitante BIGINT,

    titulo VARCHAR(160) NOT NULL,

    formato VARCHAR(10)
    NOT NULL DEFAULT 'PDF',

    origen VARCHAR(20)
    NOT NULL DEFAULT 'MANUAL',

    estado VARCHAR(20)
    NOT NULL DEFAULT 'SOLICITADO',

    parametros JSONB
    NOT NULL DEFAULT '{}'::JSONB,

    nombre_archivo VARCHAR(255),

    ruta_archivo VARCHAR(500),

    tipo_contenido VARCHAR(100),

    tamano_bytes BIGINT,

    hash_sha256 CHAR(64),

    mensaje_error TEXT,

    fecha_solicitud TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_inicio TIMESTAMP WITH TIME ZONE,

    fecha_finalizacion TIMESTAMP WITH TIME ZONE,

    fecha_expiracion TIMESTAMP WITH TIME ZONE,

    fecha_actualizacion TIMESTAMP WITH TIME ZONE
                                      NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT fk_reportes_tipo
                                      FOREIGN KEY (id_tipo_reporte)
    REFERENCES soracare.tipos_reportes (id_tipo_reporte),

    CONSTRAINT fk_reportes_usuario
    FOREIGN KEY (id_usuario_solicitante)
    REFERENCES soracare.usuarios (id_usuario),

    CONSTRAINT ck_reportes_formato
    CHECK (
              formato IN ('PDF', 'CSV', 'XLSX')
    ),

    CONSTRAINT ck_reportes_origen
    CHECK (
              origen IN ('MANUAL', 'PROGRAMADO', 'SISTEMA')
    ),

    CONSTRAINT ck_reportes_estado
    CHECK (
              estado IN (
              'SOLICITADO',
              'PROCESANDO',
              'GENERADO',
              'FALLIDO',
              'EXPIRADO'
                        )
    ),

    CONSTRAINT ck_reportes_tamano
    CHECK (
              tamano_bytes IS NULL
              OR tamano_bytes >= 0
          ),

    CONSTRAINT ck_reportes_hash
    CHECK (
              hash_sha256 IS NULL
              OR hash_sha256 ~ '^[0-9A-Fa-f]{64}$'
          ),

    CONSTRAINT ck_reportes_fechas
    CHECK (
              fecha_finalizacion IS NULL
              OR fecha_inicio IS NULL
              OR fecha_finalizacion >= fecha_inicio
          )
    );


-- =========================================================
-- 3. REGISTRO DE ACCESO A LOS REPORTES
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.accesos_reportes
(
    id_acceso_reporte BIGINT
    GENERATED BY DEFAULT AS IDENTITY
    PRIMARY KEY,

    id_reporte BIGINT NOT NULL,

    id_usuario BIGINT,

    accion VARCHAR(20) NOT NULL,

    direccion_ip INET,

    agente_usuario VARCHAR(500),

    fecha_acceso TIMESTAMP WITH TIME ZONE
                               NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_accesos_reportes_reporte
                               FOREIGN KEY (id_reporte)
    REFERENCES soracare.reportes_generados (id_reporte),

    CONSTRAINT fk_accesos_reportes_usuario
    FOREIGN KEY (id_usuario)
    REFERENCES soracare.usuarios (id_usuario),

    CONSTRAINT ck_accesos_reportes_accion
    CHECK (
              accion IN (
              'CONSULTA',
              'DESCARGA',
              'IMPRESION'
                        )
    )
    );


-- =========================================================
-- 4. ÍNDICES
-- =========================================================

CREATE INDEX IF NOT EXISTS ix_reportes_tipo
    ON soracare.reportes_generados (id_tipo_reporte);

CREATE INDEX IF NOT EXISTS ix_reportes_usuario
    ON soracare.reportes_generados (id_usuario_solicitante);

CREATE INDEX IF NOT EXISTS ix_reportes_estado
    ON soracare.reportes_generados (estado);

CREATE INDEX IF NOT EXISTS ix_reportes_fecha_solicitud
    ON soracare.reportes_generados (fecha_solicitud);

CREATE INDEX IF NOT EXISTS ix_reportes_parametros
    ON soracare.reportes_generados
    USING GIN (parametros);

CREATE INDEX IF NOT EXISTS ix_accesos_reportes_reporte
    ON soracare.accesos_reportes (id_reporte);

CREATE INDEX IF NOT EXISTS ix_accesos_reportes_usuario
    ON soracare.accesos_reportes (id_usuario);

CREATE INDEX IF NOT EXISTS ix_accesos_reportes_fecha
    ON soracare.accesos_reportes (fecha_acceso);


-- =========================================================
-- 5. FUNCIÓN PARA ACTUALIZAR LA FECHA
-- =========================================================

CREATE OR REPLACE FUNCTION soracare.actualizar_fecha_reporte()
RETURNS TRIGGER
LANGUAGE plpgsql
AS
$$
BEGIN
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$;


-- =========================================================
-- 6. TRIGGERS DE ACTUALIZACIÓN
-- =========================================================

DROP TRIGGER IF EXISTS trg_actualizar_fecha_tipo_reporte
    ON soracare.tipos_reportes;

CREATE TRIGGER trg_actualizar_fecha_tipo_reporte
    BEFORE UPDATE
    ON soracare.tipos_reportes
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_reporte();


DROP TRIGGER IF EXISTS trg_actualizar_fecha_reporte
    ON soracare.reportes_generados;

CREATE TRIGGER trg_actualizar_fecha_reporte
    BEFORE UPDATE
    ON soracare.reportes_generados
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_reporte();


