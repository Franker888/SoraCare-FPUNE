-- =========================================================
-- 1. CANALES DE NOTIFICACIÓN
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.canales_notificacion (
                                                             id_canal_notificacion SMALLINT
                                                             GENERATED BY DEFAULT AS IDENTITY,

                                                             codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_canales_notificacion
    PRIMARY KEY (id_canal_notificacion),

    CONSTRAINT uk_canales_notificacion_codigo
    UNIQUE (codigo),

    CONSTRAINT ck_canales_notificacion_codigo
    CHECK (BTRIM(codigo) <> ''),

    CONSTRAINT ck_canales_notificacion_nombre
    CHECK (BTRIM(nombre) <> '')
    );


-- =========================================================
-- 2. ESTADOS DE NOTIFICACIÓN
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.estados_notificacion (
                                                             id_estado_notificacion SMALLINT
                                                             GENERATED BY DEFAULT AS IDENTITY,

                                                             codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(255),
    es_final BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_estados_notificacion
    PRIMARY KEY (id_estado_notificacion),

    CONSTRAINT uk_estados_notificacion_codigo
    UNIQUE (codigo),

    CONSTRAINT ck_estados_notificacion_codigo
    CHECK (BTRIM(codigo) <> ''),

    CONSTRAINT ck_estados_notificacion_nombre
    CHECK (BTRIM(nombre) <> '')
    );


-- =========================================================
-- 3. PLANTILLAS DE NOTIFICACIÓN
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.plantillas_notificacion (
                                                                id_plantilla_notificacion BIGINT
                                                                GENERATED BY DEFAULT AS IDENTITY,

                                                                codigo VARCHAR(80) NOT NULL,
    id_canal_notificacion SMALLINT NOT NULL,

    nombre VARCHAR(100) NOT NULL,
    asunto VARCHAR(200),
    contenido TEXT NOT NULL,

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_creacion TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_actualizacion TIMESTAMP WITH TIME ZONE
                                      NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT pk_plantillas_notificacion
                                      PRIMARY KEY (id_plantilla_notificacion),

    CONSTRAINT uk_plantillas_notificacion_codigo
    UNIQUE (codigo),

    CONSTRAINT fk_plantillas_canal
    FOREIGN KEY (id_canal_notificacion)
    REFERENCES soracare.canales_notificacion (
                                                 id_canal_notificacion
                                             ),

    CONSTRAINT ck_plantillas_codigo
    CHECK (BTRIM(codigo) <> ''),

    CONSTRAINT ck_plantillas_nombre
    CHECK (BTRIM(nombre) <> ''),

    CONSTRAINT ck_plantillas_contenido
    CHECK (BTRIM(contenido) <> '')
    );


-- =========================================================
-- 4. COLA PRINCIPAL DE NOTIFICACIONES
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.notificaciones (
                                                       id_notificacion BIGINT
                                                       GENERATED BY DEFAULT AS IDENTITY,

                                                       id_persona BIGINT,
                                                       id_usuario BIGINT,
                                                       id_cita BIGINT,
                                                       id_pago BIGINT,

                                                       id_plantilla_notificacion BIGINT,
                                                       id_canal_notificacion SMALLINT NOT NULL,
                                                       id_estado_notificacion SMALLINT NOT NULL,

                                                       destinatario VARCHAR(255) NOT NULL,
    asunto VARCHAR(200),
    contenido TEXT NOT NULL,

    datos_contexto JSONB
    NOT NULL DEFAULT '{}'::JSONB,

    prioridad SMALLINT
    NOT NULL DEFAULT 5,

    clave_idempotencia VARCHAR(150),

    fecha_programada TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_proximo_intento TIMESTAMP WITH TIME ZONE,

    fecha_envio TIMESTAMP WITH TIME ZONE,
    fecha_entrega TIMESTAMP WITH TIME ZONE,
    fecha_cancelacion TIMESTAMP WITH TIME ZONE,

                                    cantidad_intentos SMALLINT
                                    NOT NULL DEFAULT 0,

                                    maximo_intentos SMALLINT
                                    NOT NULL DEFAULT 3,

                                    proveedor VARCHAR(80),
    referencia_proveedor VARCHAR(150),
    ultimo_error TEXT,

    fecha_creacion TIMESTAMP WITH TIME ZONE
    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    fecha_actualizacion TIMESTAMP WITH TIME ZONE
                                    NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT pk_notificaciones
                                    PRIMARY KEY (id_notificacion),

    CONSTRAINT uk_notificaciones_idempotencia
    UNIQUE (clave_idempotencia),

    CONSTRAINT fk_notificaciones_persona
    FOREIGN KEY (id_persona)
    REFERENCES soracare.personas (id_persona)
                                ON DELETE SET NULL,

    CONSTRAINT fk_notificaciones_usuario
    FOREIGN KEY (id_usuario)
    REFERENCES soracare.usuarios (id_usuario)
                                ON DELETE SET NULL,

    CONSTRAINT fk_notificaciones_cita
    FOREIGN KEY (id_cita)
    REFERENCES soracare.citas (id_cita)
                                ON DELETE SET NULL,

    CONSTRAINT fk_notificaciones_pago
    FOREIGN KEY (id_pago)
    REFERENCES soracare.pagos (id_pago)
                                ON DELETE SET NULL,

    CONSTRAINT fk_notificaciones_plantilla
    FOREIGN KEY (id_plantilla_notificacion)
    REFERENCES soracare.plantillas_notificacion (
                                                    id_plantilla_notificacion
                                                )
                                ON DELETE SET NULL,

    CONSTRAINT fk_notificaciones_canal
    FOREIGN KEY (id_canal_notificacion)
    REFERENCES soracare.canales_notificacion (
                                                 id_canal_notificacion
                                             ),

    CONSTRAINT fk_notificaciones_estado
    FOREIGN KEY (id_estado_notificacion)
    REFERENCES soracare.estados_notificacion (
                                                 id_estado_notificacion
                                             ),

    CONSTRAINT ck_notificaciones_destinatario
    CHECK (BTRIM(destinatario) <> ''),

    CONSTRAINT ck_notificaciones_contenido
    CHECK (BTRIM(contenido) <> ''),

    CONSTRAINT ck_notificaciones_contexto
    CHECK (JSONB_TYPEOF(datos_contexto) = 'object'),

    CONSTRAINT ck_notificaciones_prioridad
    CHECK (prioridad BETWEEN 1 AND 10),

    CONSTRAINT ck_notificaciones_intentos
    CHECK (
              cantidad_intentos >= 0
              AND maximo_intentos > 0
              AND cantidad_intentos <= maximo_intentos
          )
    );


-- =========================================================
-- 5. HISTORIAL DE INTENTOS DE ENVÍO
-- =========================================================

CREATE TABLE IF NOT EXISTS soracare.intentos_notificacion (
                                                              id_intento_notificacion BIGINT
                                                              GENERATED BY DEFAULT AS IDENTITY,

                                                              id_notificacion BIGINT NOT NULL,
                                                              numero_intento SMALLINT NOT NULL,

                                                              resultado VARCHAR(20) NOT NULL,
    proveedor VARCHAR(80),

    referencia_proveedor VARCHAR(150),
    codigo_respuesta VARCHAR(50),

    mensaje_error TEXT,

    respuesta_proveedor JSONB
    NOT NULL DEFAULT '{}'::JSONB,

    fecha_intento TIMESTAMP WITH TIME ZONE
                                NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT pk_intentos_notificacion
                                PRIMARY KEY (id_intento_notificacion),

    CONSTRAINT uk_intentos_notificacion_numero
    UNIQUE (id_notificacion, numero_intento),

    CONSTRAINT fk_intentos_notificacion
    FOREIGN KEY (id_notificacion)
    REFERENCES soracare.notificaciones (id_notificacion)
                            ON DELETE CASCADE,

    CONSTRAINT ck_intentos_numero
    CHECK (numero_intento > 0),

    CONSTRAINT ck_intentos_resultado
    CHECK (
              resultado IN (
              'ENVIADA',
              'ENTREGADA',
              'FALLIDA',
              'RECHAZADA'
                           )
    ),

    CONSTRAINT ck_intentos_respuesta
    CHECK (JSONB_TYPEOF(respuesta_proveedor) = 'object')
    );


