-- =========================================================
-- 7. FUNCIÓN PARA ACTUALIZAR LA FECHA DE MODIFICACIÓN
-- =========================================================

CREATE OR REPLACE FUNCTION
    soracare.actualizar_fecha_notificacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS
    trg_actualizar_fecha_plantilla
    ON soracare.plantillas_notificacion;

CREATE TRIGGER trg_actualizar_fecha_plantilla
    BEFORE UPDATE
    ON soracare.plantillas_notificacion
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_notificacion();


DROP TRIGGER IF EXISTS
    trg_actualizar_fecha_notificacion
    ON soracare.notificaciones;

CREATE TRIGGER trg_actualizar_fecha_notificacion
    BEFORE UPDATE
    ON soracare.notificaciones
    FOR EACH ROW
    EXECUTE FUNCTION soracare.actualizar_fecha_notificacion();


